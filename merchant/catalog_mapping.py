"""Column mapping: which spreadsheet column is which catalog field.

Deterministic alias matching runs first and always wins. The model is only asked about what
the aliases could not settle - an unrecognised header, or two headers competing for the same
field - and its answer is validated back against the real headers before it is applied. The
model chooses *columns*, never values: every mapped value still goes through the same
deterministic normalisation in catalog_pipeline, so a model mistake can misfile a column but
can never invent a price.
"""

